const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');

(async () => {
  const output = path.resolve('TestResults/WorkspacePrototype');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const $ = id => page.locator('#' + id);
  const pixelState = () => $('surface').evaluate(canvas => canvas.toDataURL());
  let checks = 0;
  async function check(test, message) { assert.ok(await test, message); checks++; }
  try {
    await page.goto(pathToFileURL(path.resolve('docs/prototypes/workspace.html')).href);
    await check($('notice').innerText().then(text => text.includes('Choose a target')), 'Empty selection guidance');
    await check($('sample-stroke').isDisabled(), 'No painting without activation');
    await $('select-wall').focus(); await page.keyboard.press('Enter');
    await check(page.evaluate(() => document.activeElement.id === 'prepare'), 'Selecting lesson wall hands focus to preparation');
    await page.keyboard.press('Enter');
    await check(page.evaluate(() => document.activeElement.id === 'open-materials'), 'Preparation hands focus to material setup');
    await check($('activate').isDisabled(), 'Layer painting requires material setup');
    await $('workflow').selectOption('rgba');
    await check($('activate').isEnabled(), 'Direct RGBA does not require a material');
    await $('workflow').selectOption('layers');
    await $('open-materials').focus(); await page.keyboard.press('Enter');
    await check(page.evaluate(() => document.activeElement.id === 'make-material'), 'Material panel has a logical focused action');
    await page.keyboard.press('Enter');
    await check($('activate').isEnabled(), 'Material setup enables explicit activation');
    await page.getByRole('button', { name: 'Moss First overlay Red', exact: true }).click();
    await check(page.getByRole('button', { name: 'Moss First overlay Red', exact: true }).evaluate(button => button === document.activeElement), 'Layer selection retains keyboard focus');
    const before = await pixelState();
    await $('activate').click();
    await $('sample-stroke').click();
    const painted = await pixelState();
    await check(Promise.resolve(painted !== before), 'Demo stroke changes canvas');
    await $('undo').click();
    await check(pixelState().then(value => value === before), 'One Undo restores pre-stroke state');
    await $('redo').click();
    await check(pixelState().then(value => value === painted), 'Redo restores entire stroke');
    await page.getByText('Procedural treatment · planned', { exact: true }).click();
    await $('preview-grime').click();
    await check(page.evaluate(() => document.activeElement.id === 'apply-preview'), 'Preview hands keyboard focus to Apply');
    const preview = await pixelState();
    await check($('undo').isDisabled(), 'Preview cannot alter Undo history');
    await $('cancel-preview').click();
    await check(page.evaluate(() => document.activeElement.id === 'preview-grime'), 'Cancel restores preview entry focus');
    await check(pixelState().then(value => value === painted), 'Cancel preview leaves applied strokes intact');
    await $('preview-grime').click();
    await $('apply-preview').click();
    await check(pixelState().then(value => value === preview), 'Apply matches preview');
    await $('undo').click();
    await check(pixelState().then(value => value === painted), 'Treatment is one Undo operation');
    await $('activate').click();
    const bounds = await $('surface').boundingBox();
    await page.mouse.move(bounds.x + bounds.width * .3, bounds.y + bounds.height * .4);
    await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width * .65, bounds.y + bounds.height * .5, { steps: 8 });
    await page.mouse.up();
    await check(pixelState().then(value => value !== painted), 'Pointer drag applies a demo gesture');
    await $('undo').click();
    await check(pixelState().then(value => value === painted), 'Eight drag samples are one Undo');
    await $('scenario').selectOption('stale');
    await check($('reset-dialog').isVisible(), 'Reset protects dirty demo state');
    await $('keep-demo').click();
    await check(pixelState().then(value => value === painted), 'Canceled reset preserves demo paint');
    await $('save').click();
    await $('scenario').selectOption('stale');
    await check($('recovery-panel').isVisible(), 'Topology mismatch exposes recovery');
    await check($('sample-stroke').isDisabled(), 'Topology mismatch blocks painting');
    await $('recover').click();
    await check($('recovery-details').isVisible(), 'Recovery explains separate-copy transfer');
    await $('cancel-recovery').click();
    await $('scenario').selectOption('error');
    await $('recover').click();
    await check($('activate').isEnabled(), 'Retry preserves a usable prepared target');
    await page.locator('[data-task="output"]').click();
    await $('plan-action').click();
    await check($('output-dialog').isVisible(), 'Bake operation has explicit review');
    await $('cancel-output').click();
    await page.locator('[data-task="paint"]').click();
    await page.getByText('Advanced brush settings', { exact: true }).click();
    await $('lock').check();
    await $('activate').click();
    await $('target').selectOption('cube');
    await check($('target').inputValue().then(value => value === 'wall'), 'Selection lock preserves active target');
    await $('surface').focus();
    await page.keyboard.press('Escape');
    await check($('sample-stroke').isDisabled(), 'Escape releases painting');
    await $('scenario').selectOption('sparse');
    await $('keep-coarse').click();
    await check($('target-meta').innerText().then(text => text.includes('coarse painting')), 'Sparse target can retain existing vertices');
    await $('scenario').selectOption('sparse');
    await $('prepare').click();
    await check($('target-meta').innerText().then(text => text.includes('Prepared paint data')), 'Subdivided preparation is a separate choice');
    await $('workflow').selectOption('rgba'); await $('activate').click();
    await $('channel').selectOption('Red'); await $('sample-stroke').click();
    const redDataDemo = await pixelState(); await $('undo').click();
    await $('channel').selectOption('Blue'); await $('sample-stroke').click();
    await check(pixelState().then(value => value !== redDataDemo), 'Direct channel choice changes illustrative stroke color');
    await $('save').click(); await $('surface').focus(); await page.keyboard.press('Escape');
    await check($('submesh').isDisabled(), 'Unmodeled submesh control is explicitly unavailable');
    for (const scenario of ['empty', 'setup', 'sparse', 'ready', 'mixed', 'unsupported', 'stale', 'error']) {
      await $('scenario').selectOption(scenario);
      await check($('notice').innerText().then(text => text.length > 30), `${scenario} has an explanation`);
    }
    await $('scenario').selectOption('ready');
    for (const theme of ['dark', 'light']) {
      await $('theme').selectOption(theme);
      for (const dock of ['320', '440']) {
        await $('dock').selectOption(dock);
        await check(page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${theme}/${dock} no page overflow`);
        await check(page.locator('.workbench').evaluate(panel => panel.scrollWidth <= panel.clientWidth), `${theme}/${dock} no dock overflow`);
        await page.screenshot({ path: path.join(output, `${theme}-${dock}.png`), fullPage: true });
      }
    }
    await $('target').selectOption('long');
    await check(page.locator('.workbench').evaluate(panel => panel.scrollWidth <= panel.clientWidth), 'Long target name stays within dock');
    await page.setViewportSize({ width: 390, height: 844 });
    await check(page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Small browser viewport has no horizontal overflow');
    await page.screenshot({ path: path.join(output, 'small-browser.png'), fullPage: true });
    assert.deepEqual(errors, [], 'No browser execution errors');
    console.log(`Passed ${checks} prototype checks; four dock/theme captures and one small-browser capture saved.`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
